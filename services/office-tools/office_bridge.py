#!/usr/bin/env python3
"""受控 Office 文档生成 bridge：stdin JSON -> stdout JSON（base64）。"""
import base64
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

MAX_INPUT = 200_000
MAX_SECTIONS = 100
MAX_SHEETS = 20
MAX_ROWS = 5000
MAX_SLIDES = 100


def fail(message: str) -> None:
    print(message, file=sys.stderr)
    raise SystemExit(2)


def safe_filename(value: str, default: str) -> str:
    name = (value or default).replace("\\", "/").rsplit("/", 1)[-1]
    if not name or name in {".", ".."} or len(name) > 120:
        return default
    return name


def make_docx(payload: dict, output: Path) -> None:
    from docx import Document

    title = str(payload.get("title", "")).strip()
    sections = payload.get("sections")
    if not title and not sections:
        fail("docx requires title or sections")
    if sections is None:
        sections = []
    if not isinstance(sections, list) or len(sections) > MAX_SECTIONS:
        fail("sections must be a list (<=100)")
    document = Document()
    if title:
        document.add_heading(title, level=0)
    for section in sections:
        if not isinstance(section, dict):
            fail("section must be an object")
        heading = str(section.get("heading", "")).strip()
        body = str(section.get("body", "")).strip()
        if heading:
            document.add_heading(heading, level=1)
        if body:
            for paragraph in body.split("\n\n"):
                if paragraph.strip():
                    document.add_paragraph(paragraph.strip())
    document.save(output)


def make_xlsx(payload: dict, output: Path) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Font

    sheets = payload.get("sheets")
    if not isinstance(sheets, list) or not (1 <= len(sheets) <= MAX_SHEETS):
        fail("xlsx requires 1-20 sheets")
    workbook = Workbook()
    workbook.remove(workbook.active)
    total_rows = 0
    for sheet in sheets:
        if not isinstance(sheet, dict):
            fail("sheet must be an object")
        name = str(sheet.get("name", "Sheet")).strip()[:31] or "Sheet"
        rows = sheet.get("rows")
        if not isinstance(rows, list):
            fail("sheet rows must be a list")
        total_rows += len(rows)
        if total_rows > MAX_ROWS:
            fail("xlsx rows exceed limit")
        worksheet = workbook.create_sheet(title=name)
        for row in rows:
            if not isinstance(row, list):
                fail("row must be a list")
            worksheet.append(row)
        for cell in worksheet[1] if worksheet.max_row else []:
            cell.font = Font(bold=True)
        for column in worksheet.columns:
            letter = column[0].column_letter
            width = max((len(str(cell.value or "")) for cell in column), default=8)
            worksheet.column_dimensions[letter].width = min(max(width + 2, 10), 60)
    workbook.save(output)


def make_pptx(payload: dict, output: Path) -> None:
    from pptx import Presentation
    from pptx.util import Pt

    title = str(payload.get("title", "")).strip()
    slides = payload.get("slides")
    if not isinstance(slides, list) or len(slides) > MAX_SLIDES:
        fail("slides must be a list (<=100)")
    presentation = Presentation()
    cover = presentation.slides.add_slide(presentation.slide_layouts[0])
    cover.shapes.title.text = title or "Presentation"
    if cover.placeholders[1]:
        cover.placeholders[1].text = "Generated by Yukii"
    for slide in slides:
        if not isinstance(slide, dict):
            fail("slide must be an object")
        heading = str(slide.get("title", "")).strip()
        bullets = slide.get("bullets", [])
        if not isinstance(bullets, list):
            fail("slide bullets must be a list")
        page = presentation.slides.add_slide(presentation.slide_layouts[1])
        page.shapes.title.text = heading or "Untitled"
        body = page.placeholders[1].text_frame
        body.clear()
        for index, bullet in enumerate(bullets[:20]):
            paragraph = body.paragraphs[0] if index == 0 else body.add_paragraph()
            paragraph.text = str(bullet)
            paragraph.font.size = Pt(18)
    presentation.save(output)


def main() -> None:
    raw = sys.stdin.read(MAX_INPUT + 1)
    if len(raw) > MAX_INPUT:
        fail("input too large")
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        fail("invalid JSON")
    if not isinstance(payload, dict):
        fail("input must be an object")
    kind = payload.get("format")
    if kind == "edit_xlsx":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        from openpyxl import load_workbook
        workbook = load_workbook(path)
        for item in payload.get("cells", []):
            sheet = workbook[str(item.get("sheet", ""))]
            sheet[str(item.get("cell", ""))] = item.get("value")
        output = Path(str(payload.get("output", "")))
        if not output:
            fail("output missing")
        workbook.save(output)
        data = output.read_bytes()
        print(json.dumps({
            "filename": safe_filename(str(payload.get("filename", "")), "edited.xlsx"),
            "media_type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "base64": base64.b64encode(data).decode("ascii"),
        }, ensure_ascii=False))
        return

    if kind == "edit_docx":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        from docx import Document
        document = Document(path)
        for text in payload.get("append", []):
            text = str(text).strip()
            if text:
                document.add_paragraph(text)
        output = Path(str(payload.get("output", "")))
        if not output:
            fail("output missing")
        document.save(output)
        data = output.read_bytes()
        print(json.dumps({
            "filename": safe_filename(str(payload.get("filename", "")), "edited.docx"),
            "media_type": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            "base64": base64.b64encode(data).decode("ascii"),
        }, ensure_ascii=False))
        return

    if kind == "read_docx":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        from docx import Document
        document = Document(path)
        parts = [p.text for p in document.paragraphs if p.text.strip()]
        for table in document.tables:
            for row in table.rows:
                parts.append("\t".join(cell.text.strip() for cell in row.cells))
        print(json.dumps({"text": "\n".join(parts)[:120000]}, ensure_ascii=False))
        return
    if kind == "read_pdf":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        script = os.environ.get("YUKII_PDF_TEXT_SCRIPT", "desktop/macos-native/pdf_text.swift")
        env = os.environ.copy()
        cache = os.path.abspath("target/native/module-cache")
        os.makedirs(cache, exist_ok=True)
        env["SWIFT_MODULECACHE_PATH"] = cache
        env["CLANG_MODULE_CACHE_PATH"] = cache
        result = subprocess.run(
            ["swift", script, str(path)],
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
            env=env,
        )
        if result.returncode != 0:
            fail(f"PDF text extraction failed: {result.stderr[:300]}")
        print(json.dumps({"text": result.stdout[:120000]}, ensure_ascii=False))
        return

    if kind == "read_xlsx":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        from openpyxl import load_workbook
        workbook = load_workbook(path, data_only=True, read_only=True)
        sheets = []
        for sheet in workbook.worksheets:
            rows = [[cell for cell in row] for row in sheet.iter_rows(values_only=True)]
            sheets.append({"name": sheet.title, "rows": rows[:5000]})
        print(json.dumps({"sheets": sheets}, ensure_ascii=False, default=str)[:120000])
        return
    if kind == "read_pptx":
        path = Path(str(payload.get("path", "")))
        if not path.is_file():
            fail("source file not found")
        from pptx import Presentation
        slides = []
        for index, slide in enumerate(Presentation(path).slides):
            texts = [shape.text for shape in slide.shapes if shape.has_text_frame and shape.text.strip()]
            slides.append({"index": index, "texts": texts})
        print(json.dumps({"slides": slides}, ensure_ascii=False)[:120000])
        return
    if kind == "read_pdf":
        fail("PDF text extraction requires an additional parser; not supported yet")
    if kind not in {"docx", "xlsx", "pptx", "pdf"}:
        fail("unsupported format")
    defaults = {
        "docx": ("document.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document"),
        "xlsx": ("workbook.xlsx", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"),
        "pptx": ("slides.pptx", "application/vnd.openxmlformats-officedocument.presentationml.presentation"),
        "pdf": ("document.pdf", "application/pdf"),
    }
    default_name, media_type = defaults[kind]
    filename = safe_filename(str(payload.get("filename", "")), default_name)
    with tempfile.TemporaryDirectory(prefix="yukii-office-") as directory:
        output = Path(directory) / filename
        if kind == "docx":
            make_docx(payload, output)
        elif kind == "xlsx":
            make_xlsx(payload, output)
        elif kind == "pptx":
            make_pptx(payload, output)
        else:
            source = Path(directory) / "source.docx"
            make_docx(payload, source)
            node = os.environ.get("YUKII_OFFICE_PDF_NODE", "")
            cli = os.environ.get("YUKII_OFFICE_PDF_CLI", "")
            if not node or not cli:
                fail("PDF export requires YUKII_OFFICE_PDF_NODE and YUKII_OFFICE_PDF_CLI")
            completed = subprocess.run(
                [node, cli, "convert", "--input", str(source), "--output", str(output)],
                capture_output=True,
                text=True,
                timeout=90,
                check=False,
            )
            if completed.returncode != 0:
                fail(f"PDF conversion failed: {(completed.stderr or completed.stdout)[:300]}")
            if not output.is_file() or output.stat().st_size == 0:
                fail("PDF conversion produced no output")
        data = output.read_bytes()
    if not data or len(data) > 16 * 1024 * 1024:
        fail("generated file is empty or too large")
    if kind == "pdf" and not data.startswith(b"%PDF-"):
        fail("generated file is not a PDF")
    print(json.dumps({
        "filename": filename,
        "media_type": media_type,
        "base64": base64.b64encode(data).decode("ascii"),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
